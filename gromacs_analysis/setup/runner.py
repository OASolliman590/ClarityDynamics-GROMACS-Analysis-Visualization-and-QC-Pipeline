"""Run the generated pipeline where the data lives.

- local: run in this process and return the run-report path;
- host: upload the configuration next to the data and start it in the background
  (``nohup``), returning the log path and PID;
- condor: write a run script and submit description next to the data and
  ``condor_submit`` it. The pool's shared filesystem is used (no file transfer);
  pool policy such as ``+Production = True`` comes from the condorctl config.
"""

from __future__ import annotations

import posixpath
import re
import shlex
from pathlib import Path
from typing import Dict, Optional

from .backends import Backend, BackendError, CondorctlBackend
from .jobs import new_record
from .project import Project

RUN_DIR = "clarity"
CLUSTER_RE = re.compile(r"submitted to cluster (\d+)")


def remote_paths(project: Project) -> Dict[str, str]:
    base = posixpath.join(project.root, RUN_DIR)
    return {
        "dir": base,
        "config": posixpath.join(base, "pipeline.yaml"),
        "log": posixpath.join(base, "pipeline.log"),
        "script": posixpath.join(base, "run_clarity.sh"),
        "submit": posixpath.join(base, "run_clarity.sub"),
        "exit": posixpath.join(base, "pipeline.exit"),
    }


def output_root(project: Project) -> str:
    return posixpath.join(project.root, project.output_root)


def run_local(pipeline_path: Path, continue_on_error: bool = True) -> Dict:
    from ..pipeline import run_pipeline  # noqa: WPS433
    from ..pipeline.yaml_loader import load_pipeline_config  # noqa: WPS433

    config = load_pipeline_config(Path(pipeline_path))
    results = run_pipeline(config, continue_on_error=continue_on_error)
    failed = [name for name, res in results.items()
              if isinstance(res, dict) and res.get("success") is False]
    record = new_record("analysis", "local", report=results.get("_report"),
                        last_state="failed" if failed else "completed",
                        note=f"failed stages: {', '.join(failed)}" if failed else "")
    return {"where": "local", "report": results.get("_report"), "failed_stages": failed, "record": record}


def _require_pipeline(backend: Backend, executable: str) -> None:
    check = backend.run(f"command -v {shlex.quote(executable)}")
    if not check.ok or not check.stdout.strip():
        raise BackendError(
            f"'{executable}' is not installed on {backend.label}. Install the toolkit there first, e.g. "
            "pip install --user git+https://github.com/OASolliman590/"
            "ClarityDynamics-GROMACS-Analysis-Visualization-and-QC-Pipeline"
        )


def run_on_host(backend: Backend, project: Project, yaml_text: str,
                executable: str = "gromacs-pipeline") -> Dict:
    """Upload the config and start the pipeline in the background on the data host."""
    _require_pipeline(backend, executable)
    paths = remote_paths(project)
    backend.write_text(paths["config"], yaml_text)
    inner = (
        f"{shlex.quote(executable)} --config {shlex.quote(paths['config'])} --continue-on-error; "
        f"echo $? > {shlex.quote(paths['exit'])}"
    )
    command = (
        f"cd {shlex.quote(project.root)} && rm -f {shlex.quote(paths['exit'])} && "
        f"nohup sh -c {shlex.quote(inner)} > {shlex.quote(paths['log'])} 2>&1 < /dev/null & echo $!"
    )
    result = backend.run(command)
    if not result.ok:
        raise BackendError(f"Could not start the pipeline on {backend.label}: {result.stderr.strip()}")
    pid = result.stdout.strip().splitlines()[-1] if result.stdout.strip() else None
    report = posixpath.join(output_root(project), "report.html")
    record = new_record("analysis", "host", pid=pid, log=paths["log"], exit_file=paths["exit"],
                        output_dir=output_root(project), run_dir=paths["dir"], report=report, last_state="running")
    return {"where": "host", "pid": pid, "log": paths["log"], "config": paths["config"], "report": report,
            "record": record}


def _classad(value) -> str:
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return str(value)
    return '"' + str(value).replace('"', '\\"') + '"'


def build_submit_files(project: Project, cpus: int = 4, memory_mb: int = 8192,
                       extra_attributes: Optional[Dict] = None, required_arch: Optional[str] = None,
                       executable: str = "gromacs-pipeline") -> Dict[str, str]:
    paths = remote_paths(project)
    script = "\n".join([
        "#!/bin/bash",
        "# Generated by clarity-setup: run the ClarityDynamics pipeline on the shared filesystem.",
        "set -euo pipefail",
        f"cd {shlex.quote(project.root)}",
        f"{shlex.quote(executable)} --config {shlex.quote(paths['config'])} --continue-on-error",
        "",
    ])
    lines = [
        "universe = vanilla",
        f"executable = {paths['script']}",
        f"initialdir = {paths['dir']}",
        "getenv = True",
        "should_transfer_files = NO",
        f"request_cpus = {int(cpus)}",
        f"request_memory = {int(memory_mb)}MB",
        "log = run_clarity.log",
        "output = run_clarity.out",
        "error = run_clarity.err",
        "notification = never",
    ]
    if required_arch:
        lines.append(f'requirements = (TARGET.Arch == "{required_arch}")')
    for key, value in (extra_attributes or {}).items():
        lines.append(f"+{key} = {_classad(value)}")
    lines.append("queue 1")
    return {"script": script, "submit": "\n".join(lines) + "\n"}


def _memory_mb(value) -> int:
    text = str(value).strip().upper()
    match = re.match(r"^(\d+(?:\.\d+)?)\s*(GB|G|MB|M)?$", text)
    if not match:
        raise ValueError(f"Cannot parse memory {value!r} (use e.g. 8GB or 4096MB)")
    amount = float(match.group(1))
    return int(round(amount * 1024)) if (match.group(2) or "MB") in ("GB", "G") else int(round(amount))


def submit_condor(backend: Backend, project: Project, yaml_text: str, cpus: int = 4, memory="8GB",
                  executable: str = "gromacs-pipeline") -> Dict:
    """Write config + run script + submit description next to the data and condor_submit it."""
    _require_pipeline(backend, executable)
    extra, arch = {}, None
    if isinstance(backend, CondorctlBackend):
        extra = dict(getattr(backend.config, "extra_submit_attributes", {}) or {})
        arch = getattr(backend.config, "required_arch", None)
    paths = remote_paths(project)
    files = build_submit_files(project, cpus=cpus, memory_mb=_memory_mb(memory),
                               extra_attributes=extra, required_arch=arch, executable=executable)
    backend.write_text(paths["config"], yaml_text)
    backend.write_text(paths["script"], files["script"])
    backend.write_text(paths["submit"], files["submit"])
    result = backend.run(
        f"chmod +x {shlex.quote(paths['script'])} && cd {shlex.quote(paths['dir'])} "
        f"&& condor_submit {shlex.quote(posixpath.basename(paths['submit']))}"
    )
    if not result.ok:
        raise BackendError(f"condor_submit failed: {(result.stderr or result.stdout).strip()}")
    match = CLUSTER_RE.search(result.stdout)
    if not match:
        raise BackendError(f"Could not read the cluster ID from condor_submit output:\n{result.stdout}")
    cluster = int(match.group(1))
    log = posixpath.join(paths["dir"], "run_clarity.out")
    report = posixpath.join(output_root(project), "report.html")
    record = new_record("analysis", "condor", clusters=[cluster], log=log, output_dir=output_root(project),
                        run_dir=paths["dir"], report=report, last_state="idle")
    return {"where": "condor", "cluster_id": cluster, "dir": paths["dir"], "log": log, "report": report,
            "record": record}


def pool_policy(backend: Backend) -> Dict:
    """Extra submit attributes and required architecture from a condorctl config (if any)."""
    if isinstance(backend, CondorctlBackend):
        return {"extra": dict(getattr(backend.config, "extra_submit_attributes", {}) or {}),
                "arch": getattr(backend.config, "required_arch", None)}
    return {"extra": {}, "arch": None}
