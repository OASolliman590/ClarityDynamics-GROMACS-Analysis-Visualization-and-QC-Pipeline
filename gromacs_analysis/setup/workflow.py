"""Split the analysis into parallel HTCondor jobs (a DAGMan workflow).

Units:
- one job per entry of the batch stages (one ProLIF ligand run, one distance entry,
  one TTClust system);
- one job each for the single stages that do not depend on other stages
  (QC, MD metrics, MM/PBSA, joint PCA).

A final job runs the complete configuration. Every stage has ``cache: true`` and
batch stages cache per unit, so the final job skips everything the units produced
and only builds what needs all of them (ProLIF comparison, ranking, report) - plus
any unit that failed, which has no cache entry and is therefore re-run.

Unit configurations keep the stage block unchanged except for the entry list, so
each unit builds exactly the configuration (and output folder) the full run would.
"""

from __future__ import annotations

import copy
import posixpath
import re
import shlex
from dataclasses import dataclass, field
from typing import Dict, List, Optional

import yaml

from .backends import Backend, BackendError
from .jobs import new_record
from .project import Project
from .runner import (
    CLUSTER_RE,
    RUN_DIR,
    _classad,
    _memory_mb,
    _require_pipeline,
    output_root,
    pool_policy,
)

SPLIT_STAGES = ("distance_batch", "prolif_batch", "ttclust_batch")
INDEPENDENT_STAGES = ("qc", "md", "mmpbsa", "pca_joint")
DAG_DIR = "dag"
FINAL = "final"


@dataclass
class WorkUnit:
    name: str
    stage: str
    config: Dict
    entry: Optional[str] = None
    cpus: int = 1
    parents: List[str] = field(default_factory=list)


def _job_name(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]", "_", text)


def build_units(pipeline: Dict) -> List[WorkUnit]:
    """Unit configurations for the stages that can run independently."""
    header = {k: copy.deepcopy(pipeline[k]) for k in ("project", "paths") if k in pipeline}
    units: List[WorkUnit] = []
    used = set()
    for stage in pipeline.get("run", []):
        block = pipeline.get(stage)
        if not isinstance(block, dict):
            continue
        if stage in SPLIT_STAGES:
            for entry in block.get("systems", []):
                unit_block = {**copy.deepcopy(block), "systems": [copy.deepcopy(entry)]}
                name = _job_name(f"{stage}__{entry.get('name', len(units))}")
                while name in used:
                    name += "_"
                used.add(name)
                units.append(WorkUnit(name=name, stage=stage, entry=entry.get("name"),
                                      config={**header, "run": [stage], stage: unit_block}))
        elif stage in INDEPENDENT_STAGES:
            units.append(WorkUnit(name=stage, stage=stage, config={**header, "run": [stage], stage: copy.deepcopy(block)}))
            used.add(stage)
    return units


def render_dag(units: List[WorkUnit], final_cpus: int = 4) -> str:
    lines = ["# Generated by clarity-setup: independent analysis units, then the final assembly job."]
    for unit in units:
        lines.append(f"JOB {unit.name} unit.sub")
        lines.append(f'VARS {unit.name} config="units/{unit.name}.yaml" job="{unit.name}" cpus="{unit.cpus}"')
    lines.append(f"JOB {FINAL} unit.sub")
    lines.append(f'VARS {FINAL} config="pipeline.yaml" job="{FINAL}" cpus="{int(final_cpus)}"')
    if units:
        lines.append(f"PARENT {' '.join(u.name for u in units)} CHILD {FINAL}")
    return "\n".join(lines) + "\n"


def render_submit(dag_dir: str, memory_mb: int, extra: Optional[Dict] = None, arch: Optional[str] = None) -> str:
    lines = [
        "# One submit description for every DAG node; the node passes config, job and cpus.",
        "universe = vanilla",
        f"executable = {posixpath.join(dag_dir, 'run_unit.sh')}",
        "arguments = $(config)",
        f"initialdir = {dag_dir}",
        "getenv = True",
        "should_transfer_files = NO",
        "request_cpus = $(cpus)",
        f"request_memory = {int(memory_mb)}MB",
        "log = logs/$(job).log",
        "output = logs/$(job).out",
        "error = logs/$(job).err",
        "notification = never",
    ]
    if arch:
        lines.append(f'requirements = (TARGET.Arch == "{arch}")')
    for key, value in (extra or {}).items():
        lines.append(f"+{key} = {_classad(value)}")
    lines.append("queue 1")
    return "\n".join(lines) + "\n"


def render_script(project: Project, executable: str = "gromacs-pipeline") -> str:
    # Units continue on error so a failed unit never blocks the final job; the final
    # job re-runs anything without a cache entry and reports it.
    return "\n".join([
        "#!/bin/bash",
        "# Generated by clarity-setup: run one analysis unit (or the final job) on the shared filesystem.",
        "set -uo pipefail",
        f"dag_dir={shlex.quote(dag_paths(project)['dir'])}",
        'config="$dag_dir/$1"',
        f"cd {shlex.quote(project.root)}",
        f'exec {shlex.quote(executable)} --config "$config" --continue-on-error',
        "",
    ])


def dag_paths(project: Project) -> Dict[str, str]:
    base = posixpath.join(project.root, RUN_DIR, DAG_DIR)
    return {
        "dir": base,
        "dag": posixpath.join(base, "workflow.dag"),
        "submit": posixpath.join(base, "unit.sub"),
        "script": posixpath.join(base, "run_unit.sh"),
        "config": posixpath.join(base, "pipeline.yaml"),
        "units": posixpath.join(base, "units"),
        "logs": posixpath.join(base, "logs"),
        "dagman_out": posixpath.join(base, "workflow.dag.dagman.out"),
    }


def unit_yaml(unit: WorkUnit) -> str:
    return (f"# Generated by clarity-setup: work unit {unit.name} ({unit.stage}).\n"
            + yaml.safe_dump(unit.config, sort_keys=False, allow_unicode=True))


def validate_units(units: List[WorkUnit]) -> None:
    from .generator import validate_yaml  # noqa: WPS433

    for unit in units:
        try:
            validate_yaml(unit_yaml(unit))
        except ValueError as exc:
            raise ValueError(f"Work unit {unit.name}: {exc}") from exc


def submit_dag(backend: Backend, project: Project, yaml_text: str, cpus: int = 4, memory="8GB",
               unit_cpus: int = 1, executable: str = "gromacs-pipeline") -> Dict:
    """Write units, submit description, script and DAG next to the data; ``condor_submit_dag`` it."""
    _require_pipeline(backend, executable)
    pipeline = yaml.safe_load(yaml_text)
    units = build_units(pipeline)
    for unit in units:
        unit.cpus = int(unit_cpus)
    validate_units(units)
    paths = dag_paths(project)
    policy = pool_policy(backend)
    backend.run(f"mkdir -p {shlex.quote(paths['units'])} {shlex.quote(paths['logs'])}")
    backend.write_text(paths["config"], yaml_text)
    for unit in units:
        backend.write_text(posixpath.join(paths["units"], f"{unit.name}.yaml"), unit_yaml(unit))
    backend.write_text(paths["script"], render_script(project, executable))
    backend.write_text(paths["submit"], render_submit(paths["dir"], _memory_mb(memory), policy["extra"], policy["arch"]))
    backend.write_text(paths["dag"], render_dag(units, final_cpus=cpus))
    result = backend.run(
        f"chmod +x {shlex.quote(paths['script'])} && cd {shlex.quote(paths['dir'])} "
        f"&& condor_submit_dag -force {shlex.quote(posixpath.basename(paths['dag']))}"
    )
    if not result.ok:
        raise BackendError(f"condor_submit_dag failed: {(result.stderr or result.stdout).strip()}")
    match = CLUSTER_RE.search(result.stdout)
    if not match:
        raise BackendError(f"Could not read the DAG cluster from condor_submit_dag output:\n{result.stdout}")
    cluster = int(match.group(1))
    report = posixpath.join(output_root(project), "report.html")
    record = new_record(
        "analysis", "dag", dag_cluster=cluster, clusters=[cluster], log=paths["dagman_out"],
        output_dir=output_root(project), run_dir=paths["dir"], report=report, last_state="idle",
        jobs={u.name: None for u in units} | {FINAL: None},
    )
    return {"where": "dag", "cluster_id": cluster, "units": [u.name for u in units], "dir": paths["dir"],
            "log": paths["dagman_out"], "report": report, "record": record}
